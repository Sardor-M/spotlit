"""Hash manifest for the frozen evaluation files. See ADR-0002 for why."""

from __future__ import annotations

import hashlib
from pathlib import Path

FROZEN_FILES = (
    "schema.py",
    "splits.py",
    "metrics.py",
    "harness.py",
    "rigor.py",
)

MANIFEST_NAME = "FROZEN.sha256"


def _here() -> Path:
    return Path(__file__).resolve().parent


def manifest_path() -> Path:
    return _here() / MANIFEST_NAME


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def current() -> dict[str, str]:
    return {name: digest(_here() / name) for name in FROZEN_FILES}


def recorded() -> dict[str, str]:
    path = manifest_path()
    if not path.exists():
        return {}
    entries = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        sha, name = line.split(maxsplit=1)
        entries[name.strip()] = sha
    return entries


def verify() -> list[str]:
    """Frozen files that are missing from, or disagree with, the manifest."""
    expected = recorded()
    if not expected:
        return ["<no manifest: run `tinylab-eval bless-harness`>"]
    problems = []
    have = current()
    for name in FROZEN_FILES:
        if name not in expected:
            problems.append(f"{name} (unlisted)")
        elif expected[name] != have[name]:
            problems.append(f"{name} (changed)")
    for name in expected:
        if name not in have:
            problems.append(f"{name} (listed but absent)")
    return problems


def bless() -> dict[str, str]:
    """Rewrite the manifest from the files as they are now."""
    entries = current()
    lines = [
        "# Frozen evaluation harness. Generated by `tinylab-eval bless-harness`.",
        "# Re-blessing invalidates comparability with every number recorded before it.",
        *(f"{sha}  {name}" for name, sha in sorted(entries.items())),
    ]
    manifest_path().write_text("\n".join(lines) + "\n", encoding="utf-8")
    return entries
